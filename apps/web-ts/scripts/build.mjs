#!/usr/bin/env node
/**
 * Build the static web application into `dist/`.
 *
 * The build has three parts:
 *
 *   1. `tsc` compiles the TypeScript sources into ES2020 modules in `dist/`.
 *      `dist/main.js` is the real entry point and is loaded as a module when
 *      the app is served over HTTP.
 *   2. The same sources are compiled to CommonJS and stitched into a single
 *      classic script, `dist/app.js`. Browsers refuse to load module scripts
 *      from a `file://` origin, so the classic bundle is what makes the
 *      application usable straight from the filesystem.
 *   3. The content payload is exported from the corpus and written as both
 *      `dist/content.json` and `dist/content.js` (the latter embeds the
 *      payload in the page, because `fetch()` of a neighbouring file is
 *      blocked on `file://` origins).
 *
 * Usage: node scripts/build.mjs [--skip-export] [--quiet]
 */

import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { exportContent } from './export-content.mjs';

const require = createRequire(import.meta.url);
const APP_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DIST_DIR = join(APP_DIR, 'dist');
const BUILD_DIR = join(APP_DIR, '.build');
const CJS_DIR = join(BUILD_DIR, 'cjs');
const PUBLIC_DIR = join(APP_DIR, 'public');
const CONTENT_JSON = join(PUBLIC_DIR, 'content.json');

/**
 * @param {string[]} argv
 * @returns {{skipExport: boolean, quiet: boolean}}
 */
function parseArgs(argv) {
  /** @type {{skipExport: boolean, quiet: boolean}} */
  const options = { skipExport: false, quiet: false };
  for (const arg of argv) {
    if (arg === '--skip-export') options.skipExport = true;
    else if (arg === '--quiet') options.quiet = true;
    else throw new Error(`unknown argument "${arg}"`);
  }
  return options;
}

/**
 * Run a local TypeScript compiler.
 *
 * @param {string} configPath Path of the tsconfig to build.
 * @param {string} label Human readable name for the log output.
 */
function runTsc(configPath, label) {
  const tsc = require.resolve('typescript/bin/tsc');
  const result = spawnSync(process.execPath, [tsc, '-p', configPath], { stdio: 'inherit', cwd: APP_DIR });
  if (result.status !== 0) {
    throw new Error(`tsc failed for ${label} (exit code ${result.status ?? 'unknown'})`);
  }
}

/**
 * Stitch the CommonJS build into one classic script.
 *
 * Each module is registered with a tiny loader that resolves `require()`
 * calls by file name. The result runs as a plain `<script>` on any origin,
 * including `file://`.
 *
 * @param {string} cjsDir Directory holding the CommonJS modules.
 * @param {string} entryName File name of the entry module.
 * @returns {string} The bundle source.
 */
function bundleClassicScript(cjsDir, entryName) {
  const files = readdirSync(cjsDir).filter((file) => file.endsWith('.js')).sort();
  /** @type {string[]} */
  const parts = [];
  parts.push('/* Generated by scripts/build.mjs - do not edit. */');
  parts.push('(function () {');
  parts.push("'use strict';");
  parts.push('var __defs = {};');
  parts.push('var __cache = {};');
  parts.push('function __def(id, factory) { __defs[id] = factory; }');
  parts.push('function __req(spec) {');
  parts.push('  var id = String(spec).replace(/^.*\\//, "");');
  parts.push('  if (Object.prototype.hasOwnProperty.call(__cache, id)) return __cache[id].exports;');
  parts.push('  var factory = __defs[id];');
  parts.push('  if (!factory) throw new Error("Module not found: " + spec);');
  parts.push('  var module = { exports: {} };');
  parts.push('  __cache[id] = module;');
  parts.push('  factory(module.exports, function (request) { return __req(request); }, module);');
  parts.push('  return module.exports;');
  parts.push('}');
  for (const file of files) {
    const code = readFileSync(join(cjsDir, file), 'utf8');
    parts.push(`__def(${JSON.stringify(file)}, function (exports, require, module) {`);
    parts.push(code.replace(/\r\n/g, '\n'));
    parts.push('});');
  }
  parts.push(`__req(${JSON.stringify(entryName)});`);
  parts.push('})();');
  return parts.join('\n');
}

/**
 * Build the application.
 *
 * @param {{skipExport: boolean, quiet: boolean}} options Build options.
 * @returns {Promise<void>}
 */
export async function build(options) {
  const log = (/** @type {string} */ message) => {
    if (!options.quiet) process.stdout.write(`${message}\n`);
  };

  /** Guards against two build steps writing the same output file. */
  const written = new Set();

  /**
   * Write a build output.
   *
   * @param {string} name File name inside `dist/`.
   * @param {string} contents File contents.
   */
  const writeOutput = (name, contents) => {
    if (written.has(name)) {
      throw new Error(`Build output collision: two steps both write dist/${name}`);
    }
    written.add(name);
    writeFileSync(join(DIST_DIR, name), contents, 'utf8');
  };

  log('› cleaning dist/');
  rmSync(DIST_DIR, { recursive: true, force: true });
  rmSync(CJS_DIR, { recursive: true, force: true });
  mkdirSync(DIST_DIR, { recursive: true });

  log('› compiling TypeScript (ES2020 modules)');
  runTsc(join(APP_DIR, 'tsconfig.build.json'), 'the application');

  log('› compiling TypeScript (CommonJS, for the file:// bundle)');
  mkdirSync(CJS_DIR, { recursive: true });
  runTsc(join(APP_DIR, 'tsconfig.cjs.json'), 'the file:// bundle');
  writeOutput('app.bundle.js', bundleClassicScript(CJS_DIR, 'main.js'));

  if (!options.skipExport) {
    log('› exporting the knowledge base');
    const { entryCount, domainCount } = exportContent({ out: CONTENT_JSON, quiet: true });
    log(`  ${entryCount} entries across ${domainCount} domains`);
  }
  if (!existsSync(CONTENT_JSON)) {
    throw new Error(`Missing ${CONTENT_JSON}. Run "npm run export" first.`);
  }

  const payload = readFileSync(CONTENT_JSON, 'utf8');
  writeOutput('content.json', payload);
  writeOutput(
    'content.embedded.js',
    `/* Generated by scripts/build.mjs - do not edit. */\nwindow.__ABOOK_CONTENT__ = ${payload.replace(/</g, '\\u003c')};\n`,
  );

  cpSync(join(APP_DIR, 'src', 'styles.css'), join(DIST_DIR, 'styles.css'));

  const template = readFileSync(join(APP_DIR, 'index.html'), 'utf8');
  writeOutput('index.html', template.replace('./src/styles.css', './styles.css'));

  const files = readdirSync(DIST_DIR).sort();
  const bytes = files.reduce((total, file) => total + statSync(join(DIST_DIR, file)).size, 0);
  log(`› built ${files.length} files (${(bytes / 1024).toFixed(1)} KiB) in dist/`);
}

const invokedDirectly = process.argv[1] !== undefined
  && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));

if (invokedDirectly) {
  const options = parseArgs(process.argv.slice(2));
  build(options).catch((error) => {
    process.stderr.write(`Build failed: ${error instanceof Error ? error.message : String(error)}\n`);
    process.exitCode = 1;
  });
}
